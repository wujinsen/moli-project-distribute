def expand_file() -> None:
    text = TARGET.read_text(encoding="utf-8")
    intro = """# サーティファイ 模擬問題1 · 中文详细解析

> 对应原题：`模擬問題1.md`（50 题）及 `模擬問題1_ Attempt review.html`。
> 含表格/图片的题请 **对照原 HTML 插图** 核对数值；下文已尽量写出公式与计算步骤。
> 每题解析结构：**考点 → 详细推导 → 选项分析 → 易错点**（概念题选项分析并入推导）。

"""
    text = re.sub(
        r"# サーティファイ 模擬問題1 · 中文解析\n\n> 对应原题：.*?\n\n",
        intro,
        text,
        count=1,
        flags=re.S,
    )
    text = re.sub(r"updated: 2026-07-05", "updated: 2026-07-07", text)

    for qnum, body in DETAILED.items():
        pattern = rf"(## 第 {qnum} 题.*?### 解析\n\n)(.*?)(\n\n---\n)"
        m = re.search(pattern, text, re.S)
        if not m:
            print(f"WARN: Q{qnum} not found")
            continue
        new_block = m.group(1) + body.strip() + m.group(3)
        text = text[: m.start()] + new_block + text[m.end() :]

    TARGET.write_text(text, encoding="utf-8")
    print(f"Updated {TARGET} ({len(DETAILED)} questions expanded)")


if __name__ == "__main__":
    expand_file()
