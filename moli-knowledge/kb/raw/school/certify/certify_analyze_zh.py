def parse_questions(text: str) -> list[dict]:
    blocks = re.split(r"\n## 问 (\d+)\n", text)
    questions = []
    # blocks[0] is header; then pairs (num, content)
    for i in range(1, len(blocks), 2):
        num = int(blocks[i])
        body = blocks[i + 1]
        # extract stem (before **选项**)
        parts = body.split("**选项**")
        stem_part = parts[0].strip()
        # remove status line
        stem_lines = []
        for line in stem_part.splitlines():
            if line.startswith("_") and "Mark" in line:
                continue
            stem_lines.append(line)
        stem_jp = "\n".join(stem_lines).strip()
        options = parts[1].split("**正确答案**")[0].strip() if len(parts) > 1 else ""
        ans_match = re.search(r"\*\*正确答案\*\*[：:]\s*(.+)", body)
        answer_raw = ans_match.group(1).strip() if ans_match else ""
        questions.append({
            "num": num,
            "stem_jp": stem_jp,
            "options": options,
            "answer_raw": answer_raw,
        })
    return questions


